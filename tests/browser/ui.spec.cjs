test('product pages support direct visits, reload, back, forward and header search',async({page})=>{
  await page.goto('/');
  // Keep this fixture visible regardless of products created by earlier workflow tests.
  await page.locator('#search').fill('headphones');
  await page.locator('#search').press('Enter');
  const link=page.locator('[data-product="0"] .product-open');
  await expect(link).toHaveAttribute('href','/products/0');
  await link.click();
  await expect(page).toHaveURL(/\/products\/0$/);
  expect(await page.evaluate(() => window.scrollY)).toBeLessThan(200);
  const documentWidth = await page.evaluate(() => document.documentElement.scrollWidth);
  expect(documentWidth).toBeLessThanOrEqual(page.viewportSize().width + 1);
  await expect(page.locator('#product-page h1')).toContainText('หูฟัง');
  await expect(page.locator('dialog#product-dialog')).toHaveCount(0);
  await page.locator('#add-to-cart').click();
  await expect(page.locator('#cart-count')).toHaveText('1');
  await page.goBack();
  await expect(page.locator('#storefront-home')).toBeVisible();
  await expect(page.locator('#cart-count')).toHaveText('1');
  await page.goForward();
  await expect(page.locator('#product-page')).toBeVisible();
  await page.reload();
  await expect(page.locator('#product-title')).toContainText('หูฟัง');
  await expect(page).toHaveTitle(/TrustCart/);
  await page.locator('#search').fill('กระเป๋า');
  await page.locator('#search').press('Enter');
  await expect(page).toHaveURL(/\/$/);
  await expect(page.locator('#storefront-home')).toBeVisible();
  await expect(page.locator('#products .product-name').first()).toContainText('กระเป๋า');
  await page.goto('/products/does-not-exist');
  await expect(page.locator('#product-detail h1')).toHaveText('ไม่พบสินค้า');
  await expect(page.locator('#product-page .product-verified')).toHaveCount(0);
  await page.locator('.product-page-state a').click();
  await expect(page.locator('#storefront-home')).toBeVisible();
});

